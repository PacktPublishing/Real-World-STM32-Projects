/* USER CODE BEGIN 0 */
#if USE_DEBOUNCE
/* Samples the button every DEBOUNCE_SAMPLE_MS and accepts a new level
   only after DEBOUNCE_SAMPLES equal readings in a row. Contact bounce and
   short noise spikes cannot hold the pin steady across several samples,
   so they never reach the rest of the program. */
static GPIO_PinState button_read_debounced(void)
{
  static GPIO_PinState stable = GPIO_PIN_SET;   /* released */
  static uint32_t last_sample_ms = 0;
  static uint8_t same_count = 0;

  if ((HAL_GetTick() - last_sample_ms) >= DEBOUNCE_SAMPLE_MS)
  {
    last_sample_ms = HAL_GetTick();

    GPIO_PinState raw = HAL_GPIO_ReadPin(BUTTON_GPIO_Port, BUTTON_Pin);

    if (raw == stable)
    {
      same_count = 0;                 /* nothing new: start over */
    }
    else if (++same_count >= DEBOUNCE_SAMPLES)
    {
      stable = raw;                   /* new level confirmed */
      same_count = 0;
    }
  }

  return stable;
}
#endif

