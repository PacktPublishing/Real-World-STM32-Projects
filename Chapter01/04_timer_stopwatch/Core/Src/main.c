/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_TIM2_Init();
  MX_USART2_UART_Init();
  /* USER CODE BEGIN 2 */
  /* Unbuffered stdout: each printf() goes out right away. */
  setvbuf(stdout, NULL, _IONBF, 0);

  /* TIM2 counts from 0 to 0xFFFFFFFF, one tick per microsecond. */
  HAL_TIM_Base_Start(&htim2);

  printf("\r\nStopwatch ready. Press the button to start.\r\n");

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    uint32_t now_us = __HAL_TIM_GET_COUNTER(&htim2);

    /* Unsigned subtraction gives the right interval even after the
       counter wraps from 0xFFFFFFFF back to 0 (about every 71 min). */
    if (button_event && ((now_us - last_edge_us) >= DEBOUNCE_US))
    {
      button_event = 0;

      if (HAL_GPIO_ReadPin(BUTTON_GPIO_Port, BUTTON_Pin) == GPIO_PIN_RESET)
      {
        /* The last edge is when the contact settled: use it as the
           time of the press, not the moment the debounce ended. */
        uint32_t press_us = last_edge_us;

        if (!running)
        {
          start_us = press_us;
          running = 1;
          HAL_GPIO_WritePin(LD2_GPIO_Port, LD2_Pin, GPIO_PIN_SET);
          printf("Started\r\n");
        }
        else
        {
          uint32_t elapsed_us = press_us - start_us;
          running = 0;
          HAL_GPIO_WritePin(LD2_GPIO_Port, LD2_Pin, GPIO_PIN_RESET);
          printf("Elapsed: %lu.%03lu ms\r\n",
                 elapsed_us / 1000U, elapsed_us % 1000U);
        }
      }
    }
  }
  /* USER CODE END 3 */
}

